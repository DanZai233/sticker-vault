const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('vault', {
  authorizeConnector: (id) => ipcRenderer.invoke('connector-authorize', id),
  authorizeWechatCache: () => ipcRenderer.invoke('wechat-cache-authorize'),
  syncConnector: (id, account) => ipcRenderer.invoke('connector-sync', id, account),
  disableConnector: (id) => ipcRenderer.invoke('connector-disable', id),
  copyOriginal: (id) => ipcRenderer.invoke('copy-original', id),
  insert: (id) => ipcRenderer.invoke('insert', id),
  authorizePaste: () => ipcRenderer.invoke('authorize-paste'),
  openMain: () => ipcRenderer.send('open-main'),
  setOcrEnabled: (enabled) => ipcRenderer.invoke('ocr-enabled', enabled),
  setStartupEnabled: (enabled) => ipcRenderer.invoke('startup-enabled', enabled),
  openStartupSettings: () => ipcRenderer.invoke('startup-settings'),
  onItemUpdate: (fn) => ipcRenderer.on('item-update', (_, update) => fn(update)),
  onOcrUpdate: (fn) => ipcRenderer.on('ocr-update', (_, update) => fn(update)),
  state: () => ipcRenderer.invoke('state'),
  transferState: () => ipcRenderer.invoke('transfer-state'),
  exportBackup: () => ipcRenderer.invoke('backup-export'),
  importBackup: () => ipcRenderer.invoke('backup-import'),
  saveWebDav: (input) => ipcRenderer.invoke('webdav-save', input),
  forgetWebDavPassword: () => ipcRenderer.invoke('webdav-forget'),
  testWebDav: () => ipcRenderer.invoke('webdav-test'),
  syncWebDav: () => ipcRenderer.invoke('webdav-sync'),
  cancelTransfer: () => ipcRenderer.send('transfer-cancel'),
  onTransferUpdate: (fn) => ipcRenderer.on('transfer-update', (_, update) => fn(update)),
  importFiles: (paths) => ipcRenderer.invoke('import', paths),
  pathFor: (file) => webUtils.getPathForFile(file),
  moveToFront: (id) => ipcRenderer.invoke('move-to-front', id),
  update: (id, patch) => ipcRenderer.invoke('update', id, patch),
  remove: (ids) => ipcRenderer.invoke('remove', ids),
  restoreTrash: (ids) => ipcRenderer.invoke('trash-restore', ids),
  discardTrash: (ids) => ipcRenderer.invoke('trash-discard', ids),
  importReport: (id) => ipcRenderer.invoke('import-report', id),
  retryImport: (id) => ipcRenderer.invoke('import-retry', id),
  revealReportItem: (id, key) => ipcRenderer.invoke('report-reveal', id, key),
  reveal: (id) => ipcRenderer.invoke('reveal', id),
  copyPath: (id) => ipcRenderer.invoke('copy-path', id),
  exportFiles: (ids) => ipcRenderer.invoke('export', ids),
  addFolder: (s) => ipcRenderer.invoke('folder-add', s),
  removeFolder: (p) => ipcRenderer.invoke('folder-remove', p),
  scan: () => ipcRenderer.invoke('scan'),
  drag: (id) => ipcRenderer.send('drag', id),
  onDragEnd: (fn) => ipcRenderer.on('drag-ended', fn),
  onChange: (fn) => ipcRenderer.on('changed', (_, s) => fn(s)),
  onError: (fn) => ipcRenderer.on('error', (_, s) => fn(s)),
});
