const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('vault', {
  authorizeConnector: (id) => ipcRenderer.invoke('connector-authorize', id),
  syncConnector: (id, account) => ipcRenderer.invoke('connector-sync', id, account),
  disableConnector: (id) => ipcRenderer.invoke('connector-disable', id),
  copyOriginal: (id) => ipcRenderer.invoke('copy-original', id),
  insert: (id) => ipcRenderer.invoke('insert', id),
  authorizePaste: () => ipcRenderer.invoke('authorize-paste'),
  openMain: () => ipcRenderer.send('open-main'),
  state: () => ipcRenderer.invoke('state'),
  importFiles: (paths) => ipcRenderer.invoke('import', paths),
  pathFor: (file) => webUtils.getPathForFile(file),
  update: (id, patch) => ipcRenderer.invoke('update', id, patch),
  remove: (ids) => ipcRenderer.invoke('remove', ids),
  reveal: (id) => ipcRenderer.invoke('reveal', id),
  copyPath: (id) => ipcRenderer.invoke('copy-path', id),
  exportFiles: (ids) => ipcRenderer.invoke('export', ids),
  addFolder: (s) => ipcRenderer.invoke('folder-add', s),
  removeFolder: (p) => ipcRenderer.invoke('folder-remove', p),
  scan: () => ipcRenderer.invoke('scan'),
  drag: (id) => ipcRenderer.send('drag', id),
  onChange: (fn) => ipcRenderer.on('changed', (_, s) => fn(s)),
  onError: (fn) => ipcRenderer.on('error', (_, s) => fn(s)),
});
